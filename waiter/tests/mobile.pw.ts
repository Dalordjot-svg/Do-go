import { expect, test, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { certified, nav } from './browser-fixtures'

async function checkScreen(page: Page) {
  const sizes = await page.evaluate(() => {
    const bar = document.querySelector('.app-nav')!
    const width = document.documentElement.clientWidth
    return { bodyWidth: document.documentElement.scrollWidth, width, barBottom: bar.getBoundingClientRect().bottom, viewport: window.innerHeight }
  })
  expect(sizes.bodyWidth).toBe(sizes.width)
  expect(Math.abs(sizes.barBottom - sizes.viewport)).toBeLessThanOrEqual(1)
}
test('заказ, остатки и профиль на телефоне', async ({ page }, info) => {
  await certified(page, '/#orders')
  const dir = process.env.WAITER_MOBILE_SCREENSHOTS ?? info.outputPath()
  await mkdir(dir, { recursive: true })
  const screenshot = (name: string) => page.screenshot({ path: join(dir, `${info.project.name}-${name}.png`), animations: 'disabled' })
  const tap = (name: string | RegExp) => page.getByRole('button', { name, exact: typeof name === 'string' }).tap()
  await tap(/^Все ·/)
  await expect(page.locator('.order-card').first()).toBeVisible()
  const group = page.locator('.order-grid').first()
  await expect(group).toHaveCSS('grid-template-columns', /^\d+(?:\.\d+)?px \d+(?:\.\d+)?px$/)
  await expect(page.locator('.order-card-preview').first()).not.toBeEmpty()
  await checkScreen(page)
  await screenshot('orders')

  await tap('Новый заказ')
  const picker = page.getByRole('dialog', { name: 'Столы смены' })
  await expect(picker.getByRole('heading', { name: 'У окна' })).toBeVisible()
  await expect(picker.getByRole('button', { name: /^Стол 1, Свободен$/ })).toBeVisible()
  await screenshot('tables')
  await picker.getByRole('button', { name: 'Мои', exact: true }).tap()
  await expect(picker.getByRole('button', { name: /^Стол 2,/ })).toBeVisible()
  await picker.getByRole('button', { name: 'Свободные', exact: true }).tap()
  await picker.getByRole('button', { name: /^Стол 1, Свободен$/ }).tap()
  await expect(page.getByRole('spinbutton', { name: 'Количество гостей' })).toHaveValue('2')
  await tap('Добавить ещё гостя')
  await expect(page.getByRole('spinbutton', { name: 'Количество гостей' })).toHaveValue('3')
  await screenshot('guests')
  await tap('Открыть стол')
  await expect(page.locator('.order-seat h3').getByText('Гость 3', { exact: true })).toBeVisible()
  await tap('Добавить блюдо · Гость 1')
  await expect(page.getByRole('button', { name: 'Гость 1', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await tap('Категории меню')
  await expect(page.locator('.category-tiles')).toBeVisible()
  await screenshot('categories')
  await page.locator('.category-tiles').getByRole('button', { name: /^Кофе / }).tap()
  await page.getByRole('searchbox', { name: 'Поиск по меню' }).fill('латте')
  await page.locator('.catalog-item').filter({ has: page.getByText('Латте', { exact: true }) }).getByRole('button', { name: 'Добавить', exact: true }).tap()
  await expect(page.getByRole('button', { name: 'Подтвердить · 1' })).toBeInViewport({ ratio: .9 })
  await checkScreen(page)
  await expect.poll(() => page.locator('.order-catalog').evaluate(panel => panel.scrollWidth - panel.clientWidth)).toBeLessThanOrEqual(1)
  await expect.poll(() => page.locator('.order-catalog').evaluate(panel => panel.scrollLeft)).toBe(0)
  await screenshot('menu')
  const portrait = page.viewportSize()
  if (!portrait) throw new Error('Нет размера экрана')
  await page.setViewportSize({ ...portrait, height: 440 })
  await page.getByRole('searchbox', { name: 'Поиск по меню' }).scrollIntoViewIfNeeded()
  await expect(page.getByRole('button', { name: 'Подтвердить · 1' })).toBeInViewport()
  await checkScreen(page)
  await page.setViewportSize(portrait)
  await tap('К заказу')
  const guest = page.locator('.order-seat').filter({ has: page.getByRole('heading', { name: 'Гость 1', exact: true }) })
  await expect(guest.getByText('1 × Латте')).toBeVisible()
  await tap('Подтвердить · 1')
  await expect(guest.getByText('Принято', { exact: true })).toBeVisible()

  await nav(page, 'Стоп-лист').tap()
  const stock = page.locator('.stock-group').filter({ has: page.getByRole('heading', { name: /^Осталось мало/ }) })
  await stock.getByRole('button', { name: /^Чизкейк/ }).tap()
  await page.getByLabel('Наличие').selectOption('stop')
  await tap('Сохранить наличие')
  const stopped = page.locator('.stock-group').filter({ has: page.getByRole('heading', { name: /^Закончилось/ }) })
  await expect(stopped.getByRole('button', { name: /^Чизкейк/ })).toBeVisible()
  await checkScreen(page)
  await screenshot('stock')

  await nav(page, 'Профиль').tap()
  await expect(page.getByRole('list', { name: 'Продажи: день' })).toBeVisible()
  await tap('Неделя')
  await expect(page.getByRole('list', { name: 'Продажи: неделя' })).toBeVisible()
  await tap('Месяц')
  await expect(page.getByRole('list', { name: 'Продажи: месяц' })).toBeVisible()
  await checkScreen(page)
  await screenshot('profile')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await page.locator('.app-nav button').first().evaluate(button => parseFloat(getComputedStyle(button).transitionDuration))).toBeLessThan(.01)
})
