test('офлайн-очередь восстанавливается после перезапуска и отправляет заказ и сообщение', async ({ page, context }) => {
  await certified(page)
  await page.getByRole('button', { name: /^Стол 1, Свободен/ }).click()
  await click(page, 'Открыть стол')
  await click(page, 'Добавить блюда')
  await page.locator('.catalog-grid article').filter({ has: page.getByText('Капучино', { exact: true }) }).getByRole('button', { name: 'Добавить', exact: true }).click()
  await click(page, 'К заказу')
  await expect(page.getByText('1 × Капучино')).toBeVisible()
  await click(page, 'Закрыть')
  await nav(page, 'Чаты').click()
  await expect(page.getByRole('log')).toBeVisible()
  await nav(page, 'Зал').click()
  await page.getByRole('button', { name: /^Стол 1, / }).click()
  await context.setOffline(true)
  await click(page, 'Подтвердить · 1')
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('Ожидает подтверждения')
  await click(page, 'Закрыть')
  await nav(page, 'Чаты').click()
  await page.getByLabel('Сообщение', { exact: true }).fill('Офлайн из очереди')
  await click(page, 'Отправить')
  await expect(page.getByRole('log')).toContainText('Офлайн из очереди')
  await context.setOffline(false)
  await page.reload()
  await expect(page.getByRole('log')).toContainText('Офлайн из очереди')
  await expect(page.getByRole('log').getByLabel('Подтверждено')).toHaveCount(1)
  await nav(page, 'Зал').click()
  await page.getByRole('button', { name: /^Стол 1, / }).click()
  await expect(page.getByRole('dialog').getByText('Принято', { exact: true })).toBeVisible()
})
test('телефон и планшет, темы, ссылки и сохранение поиска', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await certified(page, '/#profile')
  await expect(page.getByRole('heading', { name: 'Профиль', exact: true })).toBeVisible()
  await page.getByLabel('Тема').selectOption('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByLabel('Тема').selectOption('light')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await nav(page, 'Заказы').click()
  await page.getByLabel('Поиск заказов').fill('Стол 5')
  await nav(page, 'Стоп-лист').click()
  await expect(page.getByRole('heading', { name: 'Стоп-лист', exact: true })).toBeVisible()
  await nav(page, 'Заказы').click()
  await expect(page.getByLabel('Поиск заказов')).toHaveValue('Стол 5')
  const hasOverflow = () => page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  expect(await hasOverflow()).toBe(false)
  await page.setViewportSize({ width: 820, height: 1180 })
  await nav(page, 'Зал').click()
  await expect(page.getByRole('heading', { name: 'План зала' })).toBeVisible()
  expect(await hasOverflow()).toBe(false)
})
