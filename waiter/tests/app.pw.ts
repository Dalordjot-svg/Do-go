import { expect, test, type Page } from '@playwright/test'

import { certified, click, enter, nav } from './browser-fixtures'
const standalone = async (page: Page) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'standalone', { get: () => true }))
}
test('production gate, standalone and offline service worker', async ({ browser }) => {
  const ctx = await browser.newContext()
  const page = await ctx.newPage()
  await page.goto('http://127.0.0.1:4173/Do-go/waiter/#orders')
  await expect(page.getByRole('heading', { name: 'Установите Waiter' })).toBeVisible()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /режиме разработки/ })).toHaveCount(0)
  const scope = await page.evaluate(async () => (await navigator.serviceWorker.ready).scope)
  expect(scope).toBe('http://127.0.0.1:4173/Do-go/waiter/')
  await ctx.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Установите Waiter' })).toBeVisible()
  await standalone(page)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Добро пожаловать в Waiter' })).toBeVisible()
  await ctx.close()
})
