import { expect, test } from '@playwright/test'
import { certified, click, nav } from './browser-fixtures'

test('два браузера Firebase видят стол, очередь сообщения и результат локального сброса', async ({ browser }) => {
  const first = await browser.newContext({ baseURL: 'http://127.0.0.1:5174' })
  const second = await browser.newContext({ baseURL: 'http://127.0.0.1:5174' })
  const a = await first.newPage(), b = await second.newPage()
  await Promise.all([certified(a), certified(b, '/#hall', 'artem')])
  await expect(a.getByText('Синхронизировано', { exact: true })).toBeVisible()
  await expect(b.getByText('Синхронизировано', { exact: true })).toBeVisible()
  await a.getByRole('button', { name: /^Стол 1, Свободен/ }).click()
  await click(a, 'Открыть стол')
  await expect(b.getByRole('button', { name: /^Стол 1, Обслуживается/ })).toBeVisible()
  await click(a, 'Закрыть')
  await nav(a, 'Чаты').click()
  await nav(b, 'Чаты').click()
  const text = 'Сообщение с другого устройства ' + Date.now()
  await a.getByLabel('Сообщение', { exact: true }).fill(text)
  await click(a, 'Отправить')
  await expect(b.getByRole('log')).toContainText(text)
  await nav(a, 'Профиль').click()
  await a.getByText('Панель разработчика', { exact: true }).click()
  await click(a, 'Сбросить локальные данные')
  await click(a, 'Подтвердить локальный сброс')
  await expect(a.getByRole('heading', { name: 'Добро пожаловать в Waiter' })).toBeVisible()
  await nav(b, 'Зал').click()
  await expect(b.getByRole('button', { name: /^Стол 1, Обслуживается/ })).toBeVisible()
  await Promise.all([first.close(), second.close()])
})

test('администратор меняет меню и планировку, официант получает их в Firebase', async ({ browser }) => {
  const a = await browser.newPage({ baseURL: 'http://127.0.0.1:5174' })
  const b = await browser.newPage({ baseURL: 'http://127.0.0.1:5174' })
  await Promise.all([certified(a, '/#profile', 'ira'), certified(b, '/#hall', 'artem')])
  await expect(a.getByText('Синхронизировано', { exact: true }).first()).toBeVisible()
  await click(a, 'Панель администратора')
  const menu = a.getByRole('navigation', { name: 'Разделы управления' })
  await menu.getByRole('button', { name: 'Редактор меню', exact: true }).click()
  await click(a, /^Капучино /)
  await a.getByLabel('Название').fill('Капучино для смены')
  await a.getByLabel('Цена, ₽').fill('299.50')
  await click(a, 'Сохранить блюдо')
  await expect(a.getByText('Капучино для смены', { exact: true })).toBeVisible()
  await b.getByRole('button', { name: /^Стол 2, / }).click()
  await click(b, 'Добавить блюда')
  await b.getByLabel('Поиск по меню').fill('для смены')
  await expect(b.locator('.catalog-item')).toContainText('299,5')
  await click(b, 'Закрыть')
  await menu.getByRole('button', { name: 'Редактор зала', exact: true }).click()
  const table = a.getByRole('button', { name: /^Стол 4, / })
  const box = await table.boundingBox()
  if (!box) throw new Error('Стол отсутствует на плане')
  await a.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await a.mouse.down()
  await a.mouse.move(box.x + box.width / 2 - 15, box.y + box.height / 2 + 22, { steps: 5 })
  await a.mouse.up()
  await a.getByLabel('Мест', { exact: true }).fill('6')
  await a.getByLabel('Форма').selectOption('rectangle')
  await click(a, 'Сохранить стол')
  await expect(b.getByRole('button', { name: /^Стол 4, / })).toContainText('6 мест')
  await menu.getByRole('button', { name: 'Сотрудники', exact: true }).click()
  await click(a, /Артём Волков/)
  await a.getByLabel('Отключить').check()
  await click(a, 'Сохранить')
  await expect(b.getByRole('heading', { name: 'Выберите профиль' })).toBeVisible()
  await expect(b.getByRole('button', { name: /Артём Волков/ })).toHaveCount(0)
  await Promise.all([a.close(), b.close()])
})
